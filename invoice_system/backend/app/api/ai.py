"""
AI endpoints.

GET  /api/ai/search?q=...    Natural-language invoice search by supplier name.
POST /api/ai/qa              Ask a question about a specific invoice document.
"""

from typing import List

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session

from app.schemas import InvoiceSummary, QARequest, QAResponse
from app.services.storage import get_db
from app.services.ai import search_documents, answer_invoice_question

router = APIRouter(prefix="/api/ai", tags=["AI"])


@router.get("/search", response_model=List[InvoiceSummary])
def search_invoices_by_query(
    q: str = Query(
        ...,
        min_length=2,
        description=(
            "Natural language search query. "
            "Examples: 'facturas de Acme Corp', 'pdfs de TechSupplies', 'Acme Corp invoices'"
        ),
    ),
    db: Session = Depends(get_db),
):
    """
    Search invoices using a natural-language query.

    Extracts the supplier name from the query string and returns all
    completed invoices whose supplier_name fuzzy-matches it.
    """
    return search_documents(db, q)


@router.post("/qa", response_model=QAResponse)
def qa_invoice(payload: QARequest, db: Session = Depends(get_db)):
    """
    Ask a question about a specific invoice document.

    The answer is generated by the configured LLM (see LLM_PROVIDER / LLM_API_KEY
    in .env) using the invoice's extracted fields and raw OCR text as context.

    Returns 404 if the invoice is not found.
    Returns 503 if the LLM is unavailable or not configured.
    """
    try:
        answer = answer_invoice_question(db, payload.invoice_id, payload.question)
    except ValueError as exc:
        raise HTTPException(status_code=404, detail=str(exc))
    except (RuntimeError, ValueError) as exc:
        raise HTTPException(status_code=503, detail=str(exc))

    return QAResponse(
        invoice_id=payload.invoice_id,
        question=payload.question,
        answer=answer,
    )
